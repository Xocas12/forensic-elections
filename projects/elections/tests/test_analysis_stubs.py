def test_critical_bandwidth_is_larger_for_a_two_mode_sample_than_a_one_mode_sample():
    rng = np.random.default_rng(0)
    one = np.clip(rng.normal(50, 8, 4000), 0, 100)
    two = np.clip(np.concatenate([rng.normal(40, 4, 2000), rng.normal(85, 4, 2000)]), 0, 100)
    assert turnout_bimodality.critical_bandwidth(two) > turnout_bimodality.critical_bandwidth(one)


def test_bimodality_test_carries_the_trap_2_caveat_and_its_citation(tidy):
    result = turnout_bimodality.turnout_bimodality_test(
        tidy, election="2011-duma", n_boot=19, seed=1
    )
    assert result.method == "silverman_critical_bandwidth"
    assert 0.0 < result.pvalue <= 1.0
    assert "Silverman" in result.details["citation"]
    assert "not evidence of falsification" in result.details["caveat"]
    assert result.details["min_electorate"] == turnout_bimodality.KLIMEK_MIN_ELECTORATE


def test_the_electorate_floor_is_applied_and_counted(tidy):
    result = turnout_bimodality.turnout_bimodality_test(
        tidy, election="2011-duma", n_boot=19, seed=1
    )
    small = (tidy.loc[tidy["election"] == "2011-duma", "registered"] < 100).sum()
    assert result.details["n_excluded_small"] == small


def test_mode_locations_report_both_weightings_and_the_vote_share_at_each_mode(tidy):
    table = turnout_bimodality.turnout_mode_locations(tidy, election="2011-duma")
    assert {"mode_turnout_pct", "winner_share_at_mode_pct", "weight_by", "caveat"} <= set(
        table.columns
    )
    assert set(table["weight_by"]) == {"stations", "registered"}
    assert table["mode_turnout_pct"].between(0, 100).all()


def test_the_mode_bandwidth_exceeds_the_integer_sawtooth_period():
    """Anchor 1 finds mass on every whole number; a narrower kernel would report its teeth."""
    assert turnout_bimodality.MODE_BANDWIDTH_PP > 1.0
