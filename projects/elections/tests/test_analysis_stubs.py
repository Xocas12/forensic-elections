def test_integer_percentage_excess_returns_a_result_carrying_its_denominator(tidy):
    result = integer_percentage.integer_percentage_excess(
        tidy, election="2011-duma", n_mc=20, seed=1
    )
    assert result.settings["election"] == "2011-duma"
    assert result.settings["quantity"] == "turnout_boxes"
    # the trap-1 requirement: the number is never readable without what it is a share of
    assert result.settings["denominator_column"] == "registered"
    assert result.n_excluded_small >= 0
    assert result.per_integer.shape == (101,)
    assert np.isfinite(result.observed)


def test_winner_share_uses_ballots_counted_as_its_denominator(tidy):
    result = integer_percentage.integer_percentage_excess(
        tidy, election="2011-duma", quantity="winner_share", n_mc=20, seed=1
    )
    assert result.settings["denominator_column"] == "ballots_counted"


def test_integer_percentage_by_region_is_a_ranking(tidy):
    table = integer_percentage.integer_percentage_excess_by_region(
        tidy, election="2011-duma", n_mc=20, seed=1
    )
    assert {"region", "rank", "excess_per_unit", "election", "quantity"} <= set(table.columns)
    assert list(table["rank"]) == list(range(1, len(table) + 1))
    ordered = table["excess_per_unit"].dropna()
    assert ordered.is_monotonic_decreasing, "regions must come back sorted for the ranking"


def test_integer_percentage_by_size_band_is_ordered_by_size_not_by_the_statistic(tidy):
    from elections.features.size import SIZE_BAND_LABELS

    table = integer_percentage.integer_percentage_excess_by_size_band(
        tidy, election="2011-duma", n_mc=20, seed=1
    )
    assert {"size_band", "n_tested", "n_excluded_small", "excess_per_unit"} <= set(table.columns)
    order = [SIZE_BAND_LABELS.index(b) for b in table["size_band"]]
    assert order == sorted(order), "bands must be in size order; the question is the trend"


def test_an_unknown_election_is_refused_rather_than_silently_empty(tidy):
    with pytest.raises(ValueError, match="unknown election"):
        integer_percentage.integer_percentage_excess(tidy, election="1996-presidential")


def test_an_unknown_quantity_is_refused(tidy):
    with pytest.raises(ValueError, match="unknown quantity"):
        integer_percentage.integer_percentage_excess(
            tidy, election="2011-duma", quantity="wrong", n_mc=20
        )


