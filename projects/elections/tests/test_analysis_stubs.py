"""The analysis layer, and what keeps it honest now that two of the three anchors run.

This file used to assert that every function in ``elections.analysis`` raised
``NotImplementedError``. That guard existed so a half-finished replication could not be
mistaken for a result, and it was the right guard while the layer was stubs. Anchors 1 and 3
are now implemented, so the guard has been split in two:

* the signatures are still the contract, and are still asserted here;
* anchor 2 (:mod:`elections.analysis.comet_tail`) is still blocked on reading its primary
  source, and is still asserted to raise, with a message that says so. Implementing a
  plausible-looking tail estimator before the paper is read would produce a number with
  nothing to check it against, which is the failure mode the project is organised to avoid;
* the two implemented anchors are asserted to produce results with the documented shape, on
  the synthetic fixture, with their controls attached.

The numbers these functions produce on the real tables are not asserted here. They live in
``RESULTS.md`` and are regenerated by ``scripts/run_analysis.py``; a unit test is the wrong
place to pin a finding about an election.
"""

from __future__ import annotations

import inspect

import numpy as np
import pytest
from elections.analysis import comet_tail, integer_percentage, turnout_bimodality

ANALYSIS_MODULES = (integer_percentage, comet_tail, turnout_bimodality)

#: Anchor 2 only. These are the functions still waiting on a primary source.
BLOCKED = [
    (comet_tail.__name__, name)
    for name in comet_tail.__all__
    if callable(getattr(comet_tail, name))
]

PUBLIC = [
    (module.__name__, name)
    for module in ANALYSIS_MODULES
    for name in module.__all__
    if callable(getattr(module, name))
]


def test_there_is_one_module_per_validation_anchor():
    assert len(ANALYSIS_MODULES) == 3
    assert {m.__name__.rsplit(".", 1)[-1] for m in ANALYSIS_MODULES} == {
        "integer_percentage",
        "comet_tail",
        "turnout_bimodality",
    }


@pytest.mark.parametrize(("module_name", "name"), BLOCKED)
def test_anchor_2_still_raises_and_says_why(module_name, name, tidy):
    """Called with a real tidy frame, so it cannot pass by failing on its arguments."""
    function = getattr(comet_tail, name)
    with pytest.raises(NotImplementedError) as excinfo:
        function(tidy, election="2011-duma")
    message = str(excinfo.value)
    assert len(message) > 40, f"{name}: the message must name the remaining work"
    # The estimator is blocked on its primary source; the leave-one-region-out table is
    # blocked on the estimator. Either reason is a named blocker rather than "unfinished".
    blocked_on_source = "primary source" in message or "TO CONFIRM" in message
    blocked_on_estimator = "comet_tail_estimate" in message
    assert blocked_on_source or blocked_on_estimator, (
        f"{name}: the message must name what it is blocked on, not merely say it is unfinished"
    )


@pytest.mark.parametrize(("module_name", "name"), PUBLIC)
def test_every_analysis_function_documents_its_method_and_anchor(module_name, name):
    module = dict((m.__name__, m) for m in ANALYSIS_MODULES)[module_name]
    doc = inspect.getdoc(getattr(module, name)) or ""
    assert "Parameters" in doc
    assert "Returns" in doc
    # the module docstring is where the citation lives, and every one must have one
    module_doc = inspect.getdoc(module) or ""
    assert "docs/validation_anchors.md" in module_doc
    assert "docs/known_traps.md" in module_doc


def test_the_package_exports_every_public_function():
    for module in ANALYSIS_MODULES:
        for name in module.__all__:
            assert hasattr(module, name)


